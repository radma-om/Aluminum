/* ---------------------------- Two-step sign-in ---------------------------- */

let twoStepRequired = false;

function openTwoStep(required = false) {
    twoStepRequired = required || Boolean(ME && ME.must_setup_2fa);
    $id('twoStepBar').hidden = false;
    $id('tsClose').hidden = twoStepRequired;
    $id('tsLogout').hidden = !twoStepRequired;
    $id('tsIntro').textContent = twoStepRequired
        ? 'حسابات المديرين تحتاج التحقق بخطوتين قبل استخدام اللوحة. عند الدخول يُطلب، مع كلمة المرور، رمز من 6 أرقام يظهر في تطبيق على جوالك ويتغير كل 30 ثانية.'
        : 'عند الدخول يُطلب، مع كلمة المرور، رمز من 6 أرقام يظهر في تطبيق على جوالك ويتغير كل 30 ثانية. حتى لو عرف أحد كلمة المرور لا يستطيع الدخول بدون جوالك.';
    setStatus('tsStatus', '');
    if (ME && ME.totp_enabled && !twoStepRequired) {
        $id('tsSetup').hidden = true;
        $id('tsEnabled').hidden = false;
        $id('tsDisable').hidden = ME.role === 'manager'; // required for managers
    } else {
        startTwoStep();
    }
}

async function startTwoStep() {
    $id('tsEnabled').hidden = true;
    $id('tsSetup').hidden = false;
    $id('tsQr').innerHTML = '';
    $id('tsSecret').textContent = '…';
    $id('tsCode').value = '';
    try {
        const r = await api('POST', '/api/admin/me/2fa/setup');
        $id('tsQr').innerHTML = r.qr_svg; // generated by our server from the otpauth link
        $id('tsSecret').textContent = r.secret;
        setTimeout(() => $id('tsCode').focus(), 0);
    } catch (err) {
        setStatus('tsStatus', err.message, 'err');
    }
}

async function confirmTwoStep() {
    const code = $id('tsCode').value.replace(/\s/g, '');
    if (!/^\d{6}$/.test(code)) return setStatus('tsStatus', 'اكتب الرمز من 6 أرقام كما يظهر في التطبيق', 'err');
    try {
        await api('POST', '/api/admin/me/2fa/enable', { code });
        $id('twoStepBar').hidden = true;
        alert('تم تفعيل التحقق بخطوتين ✓\nمن الآن يُطلب الرمز من التطبيق عند كل دخول. خرجت الأجهزة الأخرى من حسابك.');
        if (twoStepRequired) return location.reload();
        ME = (await api('GET', '/api/admin/me')).user;
        applyPermissions();
    } catch (err) {
        setStatus('tsStatus', err.message, 'err');
    }
}

async function disableTwoStep() {
    const password = prompt('لإيقاف التحقق بخطوتين اكتب كلمة المرور:');
    if (password === null) return;
    try {
        ME = (await api('POST', '/api/admin/me/2fa/disable', { password })).user;
        applyPermissions();
        closeTwoStep();
        alert('تم إيقاف التحقق بخطوتين — يكفي الآن اسم المستخدم وكلمة المرور للدخول.');
    } catch (err) {
        setStatus('tsStatus', err.message, 'err');
    }
}

function closeTwoStep() {
    if (twoStepRequired) return;
    $id('twoStepBar').hidden = true;
}

