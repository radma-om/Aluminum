let auditRows = [];

const shortValue = (v) => {
    if (v === null || v === undefined || v === '') return '—';
    const text = typeof v === 'object' ? JSON.stringify(v) : String(v);
    return text.length > 120 ? text.slice(0, 120) + '…' : text;
};

function auditDetails(d) {
    if (!d) return '';
    if (d.changes) {
        const keys = Object.keys(d.changes);
        if (!keys.length) return '<span class="status-text">بدون تغيير في القيم</span>';
        return keys.map((k) => {
            const [before, after] = d.changes[k];
            return `<span class="chg"><strong>${esc(AUDIT_FIELD_NAMES[k] || k)}</strong>: <span class="old">${esc(shortValue(before))}</span> ← <span class="new">${esc(shortValue(after))}</span></span>`;
        }).join('') + (d.record ? `<small class="status-text">رقم السجل ${esc(d.record)}</small>` : '');
    }
    if (d.deleted) {
        const r = d.deleted;
        return `<span class="chg">المحذوف: <strong>${esc(r.name || r.display_name || r.username || r.title || r.ref || ('#' + (r.id || '')))}</strong></span>`
            + `<details><summary class="status-text">كل البيانات</summary><pre>${esc(JSON.stringify(r, null, 1))}</pre></details>`;
    }
    const req = d.request;
    if (req && typeof req === 'object' && Object.keys(req).length) {
        return `<details><summary class="status-text">ما أُرسل${d.created ? ` (رقم ${esc(d.created.id)})` : ''}</summary><pre>${esc(JSON.stringify(req, null, 1))}</pre></details>`;
    }
    if (typeof req === 'string') return `<small>${esc(req)}</small>`;
    return d.created ? `<small class="status-text">رقم ${esc(d.created.id)}</small>` : '';
}

const auditTime = (at) => new Date(String(at).replace(' ', 'T') + 'Z').toLocaleString('ar-OM', { dateStyle: 'medium', timeStyle: 'short' });

async function loadAudit(more = false) {
    const params = new URLSearchParams({ limit: '50' });
    const add = (k, id) => { const v = $id(id).value.trim(); if (v) params.set(k, v); };
    add('q', 'auditQ'); add('user', 'auditUser'); add('from', 'auditFrom'); add('to', 'auditTo');
    if (more && auditRows.length) params.set('before_id', auditRows[auditRows.length - 1].id);
    try {
        const r = await api('GET', '/api/admin/audit?' + params);
        auditRows = more ? auditRows.concat(r.entries) : r.entries;
        $id('auditMore').hidden = !r.more;
        $id('auditBody').innerHTML = auditRows.map((e) => `
            <tr class="${/فاشلة/.test(e.action) ? 'muted-row' : ''}">
                <td data-label="الوقت" style="white-space:nowrap"><small>${esc(auditTime(e.at))}</small></td>
                <td data-label="الحساب">${esc(e.actor)}</td>
                <td data-label="الإجراء">${/فاشلة/.test(e.action) ? '⚠️ ' : ''}${esc(e.action)}</td>
                <td data-label="التفاصيل" class="audit-details">${auditDetails(e.details)}</td>
                <td data-label="العنوان" dir="ltr"><small>${esc(e.ip || '')}</small></td>
            </tr>`).join('') || '<tr><td colspan="5">لا توجد سجلات مطابقة.</td></tr>';
        setStatus('auditStatus', '');
    } catch (err) {
        setStatus('auditStatus', err.message, 'err');
    }
}

