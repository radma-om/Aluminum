let auditRows = [];

const shortValue = (v) => {
    if (v === null || v === undefined || v === '') return '—';
    const text = typeof v === 'object' ? JSON.stringify(v) : String(v);
    return text.length > 120 ? text.slice(0, 120) + '…' : text;
};

function auditDetails(d) {
    if (!d) return '';
    if (d.changes) {
        const keys = Object.keys(d.changes);
        if (!keys.length) return '<span class="status-text">بدون تغيير في القيم</span>';
        return keys.map((k) => {
            const [before, after] = d.changes[k];
            return `<span class="chg"><strong>${esc(AUDIT_FIELD_NAMES[k] || k)}</strong>: <span class="old">${esc(shortValue(before))}</span> ← <span class="new">${esc(shortValue(after))}</span></span>`;
        }).join('') + (d.record ? `<small class="status-text">رقم السجل ${esc(d.record)}</small>` : '');
    }
    if (d.deleted) {
        const r = d.deleted;
        return `<span class="chg">المحذوف: <strong>${esc(r.name || r.display_name || r.username || r.title || r.ref || ('#' + (r.id || '')))}</strong></span>`
            + `<details><summary class="status-text">كل البيانات</summary><pre>${esc(JSON.stringify(r, null, 1))}</pre></details>`;
    }
    const req = d.request;
    if (req && typeof req === 'object' && Object.keys(req).length) {
        return `<details><summary class="status-text">ما أُرسل${d.created ? ` (رقم ${esc(d.created.id)})` : ''}</summary><pre>${esc(JSON.stringify(req, null, 1))}</pre></details>`;
    }
    if (typeof req === 'string') return `<small>${esc(req)}</small>`;
    return d.created ? `<small class="status-text">رقم ${esc(d.created.id)}</small>` : '';
}

const auditTime = (at) => new Date(String(at).replace(' ', 'T') + 'Z').toLocaleString('ar-OM', { dateStyle: 'medium', timeStyle: 'short' });

async function loadAudit(more = false) {
    const params = new URLSearchParams({ limit: '50' });
    const add = (k, id) => { const v = $id(id).value.trim(); if (v) params.set(k, v); };
    add('q', 'auditQ'); add('user', 'auditUser'); add('from', 'auditFrom'); add('to', 'auditTo');
    if (more && auditRows.length) params.set('before_id', auditRows[auditRows.length - 1].id);
    try {
        const r = await api('GET', '/api/admin/audit?' + params);
        auditRows = more ? auditRows.concat(r.entries) : r.entries;
        $id('auditMore').hidden = !r.more;
        $id('auditBody').innerHTML = auditRows.map((e) => `
            <tr class="${/فاشلة/.test(e.action) ? 'muted-row' : ''}">
                <td style="white-space:nowrap"><small>${esc(auditTime(e.at))}</small></td>
                <td>${esc(e.actor)}</td>
                <td>${/فاشلة/.test(e.action) ? '⚠️ ' : ''}${esc(e.action)}</td>
                <td class="audit-details">${auditDetails(e.details)}</td>
                <td dir="ltr"><small>${esc(e.ip || '')}</small></td>
            </tr>`).join('') || '<tr><td colspan="5">لا توجد سجلات مطابقة.</td></tr>';
        setStatus('auditStatus', '');
    } catch (err) {
        setStatus('auditStatus', err.message, 'err');
    }
}

/* ---------------------------- Backup by email ---------------------------- */

async function loadOffsite() {
    if (!ME || ME.role !== 'manager') return;
    const s = await api('GET', '/api/admin/offsite-backup');
    const box = $id('offsiteBox');
    $id('offsiteSend').hidden = !s.configured;
    if (!s.configured) {
        box.innerHTML = '⚠️ <strong>غير مفعّل:</strong> النسخ محفوظة على هذا الخادم فقط. لإرسال نسخة يومية إلى بريدك أضف في متغيرات البيئة على Hostinger: '
            + '<code dir="ltr">SMTP_HOST</code> و<code dir="ltr">SMTP_PORT</code> و<code dir="ltr">SMTP_USER</code> و<code dir="ltr">SMTP_PASS</code> و<code dir="ltr">BACKUP_EMAIL_TO</code> ثم أعد النشر.';
        return;
    }
    const last = s.last;
    box.innerHTML = `✓ <strong>مفعّل:</strong> نسخة يومية تُرسل إلى <span dir="ltr">${esc(s.to.join(', '))}</span> عبر <span dir="ltr">${esc(s.host)}:${esc(s.port)}</span>.<br>`
        + (last
            ? (last.ok
                ? `<span class="ok" style="color:var(--success)">آخر إرسال ناجح: ${esc(auditTime(last.at))} (${Math.round((last.bytes || 0) / 1024)} KB)</span>`
                : `<span style="color:var(--danger)">آخر محاولة فشلت (${esc(auditTime(last.at))}): ${esc(last.error || '')}</span>`
                    + (s.last_ok_at ? `<br>آخر إرسال ناجح: ${esc(auditTime(s.last_ok_at))}` : ''))
            : 'لم تُرسل أي نسخة بعد — اضغط «أرسل نسخة الآن» للتجربة.');
}

async function sendOffsiteNow() {
    setStatus('offsiteStatus', 'جاري التجهيز والإرسال...');
    $id('offsiteSend').disabled = true;
    try {
        const r = await api('POST', '/api/admin/offsite-backup');
        setStatus('offsiteStatus', `أُرسلت ✓ إلى ${r.to.join(', ')} — تأكد من وصولها إلى البريد (وافحص مجلد الرسائل غير المرغوبة)`, 'ok');
    } catch (err) {
        setStatus('offsiteStatus', err.message, 'err');
    } finally {
        $id('offsiteSend').disabled = false;
        loadOffsite().catch(() => {});
    }
}

const switchTabBeforeSecurity = window.switchTab;
window.switchTab = function (tabId) {
    switchTabBeforeSecurity(tabId);
    if (online && tabId === 'audit' && ME && ME.role === 'manager') loadAudit();
};
