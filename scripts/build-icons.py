"""Build the self-hosted icon set (public/icons.css + public/fonts/fa-*-<hash>.woff2).

Only the Font Awesome icons the pages use are kept (about 100), so the fonts
are a few KB instead of ~280 KB from a CDN, and they come from this server
(cached a year by version) instead of a third party on every first visit.

Run again after using a new icon (fa-…) anywhere in public/ or src/:
  npm pack @fortawesome/fontawesome-free@6.4.0 && tar xzf fortawesome-fontawesome-free-6.4.0.tgz
  python3 -m venv venv && venv/bin/pip install fonttools brotli
  venv/bin/python scripts/build-icons.py path/to/package
Font Awesome Free: icons CC BY 4.0, fonts SIL OFL 1.1, code MIT.
"""
import re, sys, pathlib, hashlib
from fontTools import subset

ROOT = pathlib.Path(__file__).resolve().parent.parent
FA = pathlib.Path(sys.argv[1])
used = set()
for f in list((ROOT / 'public').glob('*.js')) + list((ROOT / 'public').glob('*.html')) + list((ROOT / 'src').glob('*.js')):
    used |= set(re.findall(r'\bfa-[a-z0-9-]+', f.read_text(encoding='utf-8')))

def rules(css):
    """{name: codepoint} from '.fa-name::before { content: "\\f123"; }' (several selectors per rule)."""
    out = {}
    for sels, cp in re.findall(r'((?:\.fa-[a-z0-9-]+::?before,?\s*)+)\{\s*content:\s*"\\([0-9a-f]+)"', css):
        for name in re.findall(r'\.(fa-[a-z0-9-]+)::?before', sels):
            out[name] = cp
    return out

core = rules((FA / 'css/fontawesome.css').read_text())
brands = rules((FA / 'css/brands.css').read_text())
icons = {n: core[n] for n in sorted(used) if n in core}
brand_icons = {n: brands[n] for n in sorted(used) if n in brands and n not in core}

def make(src, dst, cps):
    opts = subset.Options(); opts.flavor = 'woff2'; opts.layout_features = []; opts.name_IDs = ['*']; opts.notdef_outline = True
    font = subset.load_font(str(src), opts)
    s = subset.Subsetter(opts); s.populate(unicodes=[int(c, 16) for c in cps]); s.subset(font)
    subset.save_font(font, str(dst), opts)
    return dst.stat().st_size

out = ROOT / 'public/fonts'
for old in out.glob('fa-*.woff2'):
    old.unlink()
names = {}
def build(kind, src, cps):
    # The file's name carries its content's hash: a new icon set is a new address (fonts are cached 30 days)
    tmp = out / f'fa-{kind}.tmp.woff2'
    make(src, tmp, cps)
    name = f'fa-{kind}-{hashlib.sha256(tmp.read_bytes()).hexdigest()[:8]}.woff2'
    tmp.rename(out / name)
    names[kind] = name
    return (out / name).stat().st_size
sizes = {
    'solid': build('solid', FA / 'webfonts/fa-solid-900.ttf', icons.values()),
    'regular': build('regular', FA / 'webfonts/fa-regular-400.ttf', icons.values()),
    'brands': build('brands', FA / 'webfonts/fa-brands-400.ttf', brand_icons.values()),
}
face = lambda fam, w, k: f'@font-face{{font-family:"{fam}";font-style:normal;font-weight:{w};font-display:block;src:url("fonts/{names[k]}") format("woff2")}}'
css = [
    '/* Font Awesome Free 6.4.0 (icons CC BY 4.0, fonts SIL OFL 1.1, code MIT) — only the icons this app uses.',
    '   Generated by scripts/build-icons.py: do not edit by hand. */',
    face('Font Awesome 6 Free', 900, 'solid'), face('Font Awesome 6 Free', 400, 'regular'), face('Font Awesome 6 Brands', 400, 'brands'),
    '.fa,.fas,.fa-solid,.far,.fa-regular,.fab,.fa-brands{-moz-osx-font-smoothing:grayscale;-webkit-font-smoothing:antialiased;display:var(--fa-display,inline-block);font-style:normal;font-variant:normal;line-height:1;text-rendering:auto}',
    '.fa,.fas,.fa-solid{font-family:"Font Awesome 6 Free";font-weight:900}.far,.fa-regular{font-family:"Font Awesome 6 Free";font-weight:400}.fab,.fa-brands{font-family:"Font Awesome 6 Brands";font-weight:400}',
]
for n, cp in {**icons, **brand_icons}.items():
    css.append(f'.{n}::before{{content:"\\{cp}"}}')
(ROOT / 'public/icons.css').write_text('\n'.join(css) + '\n', encoding='utf-8')
missing = sorted(n for n in used if n not in core and n not in brands and n not in ('fa-solid', 'fa-regular', 'fa-brands'))
print('files', names)
print('icons', len(icons), 'brands', len(brand_icons), 'sizes', sizes, 'not icons:', missing)
